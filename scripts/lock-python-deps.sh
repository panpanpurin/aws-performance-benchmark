#!/usr/bin/env bash
#
#   bash scripts/lock-python-deps.sh

set -euo pipefail
# shellcheck source=lib.sh
source "$(cd "$(dirname "$0")" && pwd)/lib.sh"

REQ="$ROOT/apps/csv-processor/requirements.txt"

# Must match the FROM line in apps/csv-processor/Dockerfile.
BASE_IMAGE="python:3.12-slim@sha256:57cd7c3a7a273101a6485ba99423ee568157882804b1124b4dd04266317710de"

section "python dependency lock"

if ! docker info >/dev/null 2>&1; then
  echo "FAIL Docker is not running - start Docker Desktop and re-run." >&2
  exit 1
fi

dockerfile_digest="$(grep -oE 'python:3\.12-slim@sha256:[0-9a-f]{64}' "$ROOT/apps/csv-processor/Dockerfile" | head -1)"
if [[ -n "$dockerfile_digest" && "$dockerfile_digest" != "$BASE_IMAGE" ]]; then
  echo "FAIL BASE_IMAGE in this script does not match apps/csv-processor/Dockerfile:" >&2
  echo "       script:     $BASE_IMAGE" >&2
  echo "       Dockerfile: $dockerfile_digest" >&2
  exit 1
fi

# Feed the resolver only the direct requirements. After the first run the
# uncommented lines are the whole closure, so recover the inputs from the header
# block instead - otherwise a removed dependency could never leave the lock.
if grep -q '^# GENERATED by scripts/lock-python-deps.sh' "$REQ"; then
  direct="$(sed -n '/^# Direct dependencies (the resolver input):$/,/^#$/p' "$REQ" \
            | sed -n 's/^#   //p')"
  if [[ -z "$direct" ]]; then
    echo "FAIL $REQ is marked generated but its direct-dependency header is missing." >&2
    echo "     Restore the direct dependencies by hand, or check out an earlier revision." >&2
    exit 1
  fi
  echo "re-locking from the recorded direct dependencies:"
else
  direct="$(grep -vE '^\s*(#|$)' "$REQ")"
  echo "locking from the direct dependencies in requirements.txt:"
fi
printf '%s\n' "$direct" | sed 's/^/  /'

tmp_in="$(mktemp)"
tmp_out="$(mktemp)"
trap 'rm -f "$tmp_in" "$tmp_out"' EXIT
printf '%s\n' "$direct" > "$tmp_in"

echo "resolving inside $BASE_IMAGE ..."

# stdin rather than a bind mount: under Git Bash the temp path is an MSYS path,
# which Docker Desktop does not mount.
# --only-binary=:all: matches the Dockerfile - wheels only, never a local build.
docker run --rm -i --platform linux/amd64 \
  "$BASE_IMAGE" \
  sh -c 'cat > /tmp/req.txt &&
         pip install --quiet --no-cache-dir --only-binary=:all: -r /tmp/req.txt >/dev/null 2>&1 &&
         pip freeze --all --exclude pip --exclude setuptools --exclude wheel' \
  < "$tmp_in" > "$tmp_out"

if [[ ! -s "$tmp_out" ]]; then
  echo "FAIL resolver produced no output" >&2
  exit 1
fi

{
  echo "# Full transitive dependency closure, pinned exactly."
  echo "#"
  echo "# GENERATED by scripts/lock-python-deps.sh - do not hand-edit."
  echo "# Resolved for linux/amd64 CPython 3.12 inside the same digest-pinned base"
  echo "# image the Dockerfile builds from. Re-run the script after changing a"
  echo "# direct dependency below, and commit the result."
  echo "#"
  echo "# Direct dependencies (the resolver input):"
  printf '%s\n' "$direct" | sed 's/^/#   /'
  echo "#"
  echo "# Resolved $(date -u +%Y-%m-%d) against:"
  echo "#   $BASE_IMAGE"
  echo ""
  sort -f "$tmp_out"
} > "$REQ"

ok "wrote $(printf '%s\n' "$(grep -cvE '^\s*(#|$)' "$REQ")") pinned packages to apps/csv-processor/requirements.txt"
echo
echo "numpy resolved to: $(grep -iE '^numpy==' "$REQ" || echo '(not present)')"
