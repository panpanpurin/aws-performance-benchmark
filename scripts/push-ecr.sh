#!/usr/bin/env bash
# Build and push EC2/ECS (:latest) and Lambda (:lambda) images to ECR.
# Lambda needs a single-platform Docker V2 manifest (not an OCI image index).
#
#   ./scripts/push-ecr.sh
#   ./scripts/push-ecr.sh anilove
#   REGION=ap-northeast-1 PROJECT=aws-perf-bench ./scripts/push-ecr.sh all
#
# Records every pushed digest in terraform/image-digests.auto.tfvars, which
# terraform loads automatically. Pinning by digest is what stops a rebuild
# halfway through a campaign from silently changing what later repetitions run.

set -euo pipefail

REGION="${REGION:-ap-northeast-1}"
PROJECT="${PROJECT:-aws-perf-bench}"
FILTER="${1:-all}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

need() { command -v "$1" >/dev/null 2>&1 || { echo "ERROR: '$1' not found in PATH" >&2; exit 127; }; }
need aws
need docker

ACCOUNT="$(aws sts get-caller-identity --query Account --output text)"
REGISTRY="${ACCOUNT}.dkr.ecr.${REGION}.amazonaws.com"

echo "Account  ${ACCOUNT}"
echo "Region   ${REGION}"
echo "Registry ${REGISTRY}"
echo

DIGEST_FILE="${ROOT}/terraform/image-digests.auto.tfvars"

# Preloaded from the existing file so pushing one app does not blank the digests
# of the other two.
declare -A DIGESTS
if [[ -f "$DIGEST_FILE" ]]; then
  while IFS= read -r line; do
    line="${line%$'\r'}"
    [[ "$line" =~ ^([a-z_]+)[[:space:]]*=[[:space:]]*\"(.*)\"$ ]] || continue
    DIGESTS["${BASH_REMATCH[1]}"]="${BASH_REMATCH[2]}"
  done <"$DIGEST_FILE"
fi

write_digest_file() {
  {
    echo "# GENERATED by scripts/push-ecr.sh. Do not hand-edit."
    echo "# Loaded automatically by terraform; delete the file to fall back to tags."
    echo "# Written $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo
    for v in image_digest_anilove image_digest_csv image_digest_thumbnail \
      image_digest_lambda_anilove image_digest_lambda_csv image_digest_lambda_thumbnail; do
      printf '%-30s = "%s"\n' "$v" "${DIGESTS[$v]:-}"
    done
  } >"$DIGEST_FILE"
}

echo "Logging in to ECR..."
# Git Bash/MSYS: prevent path conversion breaking the registry URL
export MSYS_NO_PATHCONV=1
aws ecr get-login-password --region "$REGION" |
  docker login --username AWS --password-stdin "$REGISTRY"

push_one() {
  local name="$1" dir="$2" repo="$3" dockerfile="$4" tag="$5" for_lambda="$6" var="$7"
  local context="${ROOT}/${dir}"
  local local_ref="${repo}:${tag}"
  local remote_ref="${REGISTRY}/${repo}:${tag}"

  echo
  echo "==> Build ${name} (${tag}) from ${dockerfile}"

  # Relative context: $ROOT is an MSYS path Docker Desktop cannot resolve, and
  # this repo path also has a space and a non-ASCII character.
  (
    cd "$context" || exit 1
    if [[ "$for_lambda" == "1" ]]; then
      # Classic builder avoids OCI index / attestations that Lambda rejects
      DOCKER_BUILDKIT=0 docker build --platform linux/amd64 \
        -t "$local_ref" -f "$dockerfile" . ||
        docker buildx build --platform linux/amd64 --provenance=false --sbom=false --load \
          -t "$local_ref" -f "$dockerfile" .
    else
      docker build --platform linux/amd64 \
        -t "$local_ref" -f "$dockerfile" .
    fi
  )

  docker tag "$local_ref" "$remote_ref"
  echo "==> Push ${remote_ref}"
  docker push "$remote_ref"

  if [[ "$for_lambda" == "1" ]]; then
    media="$(aws ecr batch-get-image \
      --region "$REGION" \
      --repository-name "$repo" \
      --image-ids "imageTag=${tag}" \
      --query 'images[0].imageManifestMediaType' \
      --output text)"
    echo "    mediaType=${media}"
    if [[ "$media" == *index* ]]; then
      echo "ERROR: Lambda image is still an OCI index. Rebuild with DOCKER_BUILDKIT=0." >&2
      exit 1
    fi
  fi

  # The tag moves on the next push; the digest is what makes a run reproducible.
  local digest
  digest="$(aws ecr describe-images \
    --region "$REGION" \
    --repository-name "$repo" \
    --image-ids "imageTag=${tag}" \
    --query 'imageDetails[0].imageDigest' \
    --output text)"
  if [[ -z "$digest" || "$digest" == "None" ]]; then
    echo "ERROR: could not read digest for ${repo}:${tag}" >&2
    exit 1
  fi
  DIGESTS["$var"]="$digest"
  echo "    digest=${digest}"
}

push_app() {
  local name="$1" dir="$2" repo="$3" key="$4"
  push_one "$name" "$dir" "$repo" "Dockerfile" "latest" 0 "image_digest_${key}"
  push_one "$name" "$dir" "$repo" "Dockerfile.lambda" "lambda" 1 "image_digest_lambda_${key}"
}

case "$FILTER" in
  all)
    push_app anilove apps/anilove "${PROJECT}/anilove" anilove
    push_app csv apps/csv-processor "${PROJECT}/csv-processor" csv
    push_app thumbnail apps/thumbnail-generator "${PROJECT}/thumbnail-generator" thumbnail
    ;;
  anilove) push_app anilove apps/anilove "${PROJECT}/anilove" anilove ;;
  csv) push_app csv apps/csv-processor "${PROJECT}/csv-processor" csv ;;
  thumbnail) push_app thumbnail apps/thumbnail-generator "${PROJECT}/thumbnail-generator" thumbnail ;;
  *)
    echo "Usage: $0 [all|anilove|csv|thumbnail]" >&2
    exit 1
    ;;
esac

write_digest_file

echo
echo "Done. Filter=${FILTER}"
echo "Pinned digests -> ${DIGEST_FILE#"$ROOT"/}"
for v in "${!DIGESTS[@]}"; do
  [[ -n "${DIGESTS[$v]}" ]] && printf '  %-30s %s\n' "$v" "${DIGESTS[$v]}"
done | sort
echo
echo "Next: enable_ec2/ecs/lambda = true in terraform.tfvars, then make apply"
